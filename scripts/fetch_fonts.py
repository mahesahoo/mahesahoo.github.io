"""fetch_fonts.py — self-host the two typefaces instead of loading them from Google.

Writes woff2 files into `fonts/` and `src/fonts.css` with matching @font-face
rules. Only the Latin subset is fetched, and Google serves *variable* files, so
both Inter weights are literally the same bytes — they get deduplicated into a
single file with a weight range. Result: 3 requests instead of Google's 26
@font-face blocks across 9 files.

    python scripts/fetch_fonts.py && npm run build

Re-run only when the weights below change.
"""
import hashlib
import pathlib
import re
import shutil
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONTS = ROOT / "fonts"
CSS_OUT = ROOT / "src" / "fonts.css"

UA = ("Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/126.0 Safari/537.36")

SPEC = (
    "https://fonts.googleapis.com/css2"
    "?family=Playfair+Display:ital,wght@0,400;0,500;1,400"
    "&family=Inter:wght@400;500"
    "&display=swap"
)

BLOCK = re.compile(r"/\*\s*([\w-]+)\s*\*/\s*@font-face\s*\{(.*?)\}", re.S)
LATIN = re.compile(r"unicode-range:\s*U\+0000-00FF")
LATIN_RANGE = ("U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, "
               "U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, "
               "U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD")


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    return urllib.request.urlopen(req, timeout=30).read()


def main():
    css = fetch(SPEC).decode()

    # (family, style) -> {weight: bytes}, identical bytes collapsed by hash
    groups = {}
    for subset, body in BLOCK.findall(css):
        if subset != "latin" and not LATIN.search(body):
            continue
        family = re.search(r"font-family:\s*'([^']+)'", body).group(1)
        weight = int(re.search(r"font-weight:\s*(\d+)", body).group(1))
        style = re.search(r"font-style:\s*(\w+)", body).group(1)
        url = re.search(r"url\((https://[^)]+\.woff2)\)", body).group(1)
        groups.setdefault((family, style), {})[weight] = fetch(url)

    if FONTS.exists():
        shutil.rmtree(FONTS)
    FONTS.mkdir()

    rules = []
    for (family, style), weights in sorted(groups.items()):
        # Every weight with identical bytes is the same variable file.
        unique = {}
        for weight, data in weights.items():
            unique.setdefault(hashlib.sha256(data).hexdigest(), []).append(weight)

        for digest, wlist in unique.items():
            data = weights[wlist[0]]
            slug = family.lower().replace(" ", "-")
            name = f"{slug}{'-italic' if style == 'italic' else ''}.woff2"
            (FONTS / name).write_bytes(data)
            lo, hi = min(wlist), max(wlist)
            weight_css = f"{lo} {hi}" if lo != hi else str(lo)
            rules.append(
                f"@font-face {{\n"
                f"  font-family: '{family}';\n"
                f"  font-style: {style};\n"
                f"  font-weight: {weight_css};\n"
                f"  font-display: swap;\n"
                f"  src: url('fonts/{name}') format('woff2');\n"
                f"  unicode-range: {LATIN_RANGE};\n"
                f"}}"
            )
            print(f"{name:<28} {len(data) / 1024:6.1f} KB  weights {weight_css}")

    CSS_OUT.write_text(
        "/* Generated by scripts/fetch_fonts.py — do not edit by hand. */\n"
        + "\n".join(rules) + "\n"
    )
    total = sum(f.stat().st_size for f in FONTS.iterdir())
    print(f"\n{len(rules)} files, {total / 1024:.1f} KB total -> {CSS_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
